"""The beat, as a card.

The narration used to be a wall of prose with a 339px square dropped into
it: no hierarchy, no margins, and the dish hugging the left edge with the
whole right half of the terminal empty. This module renders the same copy
as a small instrument panel — a header rule, one headline, a stat strip,
the dish on the left with the explanation wrapped into a real measure on
the right, a caption, and a command table.

Everything here is plain ANSI truecolor. Kitty renders it; a terminal
that does not understand SGR still shows readable text, because the
escapes are only ever around the words.

Layout is decided by width:
  * cols >= 96 and a dish present -> two columns (dish left, text right)
  * otherwise                     -> stacked card, no dish
"""
from __future__ import annotations

import re

# ── palette (truecolor, Tokyo Night) ────────────────────────────────────────
FG = "\x1b[38;2;192;202;245m"
WHITE = "\x1b[38;2;236;240;250m"
SOFT = "\x1b[38;2;169;177;214m"
DIM = "\x1b[38;2;110;120;160m"
ACCENT = "\x1b[38;2;125;207;255m"
GREEN = "\x1b[38;2;158;206;106m"
BOLD = "\x1b[1m"
ITALIC = "\x1b[3m"
RST = "\x1b[0m"

_ANSI = re.compile(r"\x1b\[[0-9;]*m")
DISH_COLS = 24          # fallback; the worker passes the real width
MIN_GUTTER = 40
TEXT_INSET = 8          # breathing room between the dish and the copy
MAX_COLS = 104
LABEL = "vivarium"


def plain(s: str) -> str:
    return _ANSI.sub("", s)


def width(s: str) -> int:
    return len(plain(s))


def wrap(text: str, cols: int) -> list[str]:
    """Word wrap that never breaks a word (the old block split 'fingerprint')."""
    out: list[str] = []
    for para in text.split("\n"):
        para = " ".join(para.split())
        if not para:
            out.append("")
            continue
        cur = ""
        for word in para.split(" "):
            cand = f"{cur} {word}".strip()
            if width(cand) <= cols:
                cur = cand
            else:
                if cur:
                    out.append(cur)
                cur = word
        if cur:
            out.append(cur)
    return out


def _rule(cols: int, left: str = "", right: str = "") -> str:
    """A dim hairline with optional labels at the ends."""
    left_s = f" {left} " if left else ""
    right_s = f" {right} " if right else ""
    fill = max(0, cols - width(left_s) - width(right_s))
    line = "─" * fill
    return f"{DIM}{left_s}{line}{right_s}{RST}"


def _pad(s: str, n: int) -> str:
    return s + " " * max(0, n - width(s))


def parse(body: str, marker: str) -> dict:
    """Pull the structured facts out of the copy the acts module produced.

    The copy is generated by us (seeding.onboard_message + acts), so the
    numbers are stable; anything that does not match is simply omitted
    rather than invented.
    """
    # The marker is the wordmark, and it is not always before the portrait:
    # an arrival card is announcement, face, copy. Splitting on the bare
    # word meant the first occurrence of "vivarium" inside the copy
    # ("Meet it: /vivarium show Eidos_x") cut the card in half and left
    # "Meet it: /" as the headline. When there is a face, the face is the
    # seam: facts above it, copy below it.
    m = _ART_RE.search(body or "")
    art: list = []
    art_id = ""
    if m:
        head, tail = body[:m.start()], body[m.end():]
        art = m.group(2).split("\n")
        art_id = m.group(1)
    else:
        head, _, tail = body.partition(marker)
    facts: dict = {"head": head.strip(), "tail": tail.strip(),
                   "art": art, "art_id": art_id}
    for key, pattern in (
        ("era", r"era (\d+)"),
        ("species", r"Seeded (\d+) species"),
        ("canon", r"(\d+) canon"),
        ("private", r"(\d+) private"),
    ):
        m = re.search(pattern, head, re.IGNORECASE)
        if m:
            facts[key] = int(m.group(1))
    m = re.search(r"(The [^.]*die-off[^.]*\.)", head, re.IGNORECASE)
    if m:
        facts["flavor"] = m.group(1).strip()
    return facts


def _lead_split(text: str) -> int:
    """Length of the first sentence: the clause that carries the point."""
    norm = " ".join(text.split())
    m = re.match(r"(.+?[.!?])(\s|$)", norm)
    return len(m.group(1)) if m else 0


def styled_paragraph(text: str, width: int, lead: bool = True) -> list[str]:
    """Wrap one paragraph, its opening clause set apart in bold white.

    The first sentence gets its own line(s): a lead that stands alone is
    what makes the paragraph readable at a glance, and it is also the only
    way to guarantee the bold run does not start mid-line and stop there.
    """
    norm = " ".join(text.split())
    cut = _lead_split(norm) if lead else 0
    head, rest = norm[:cut].strip(), norm[cut:].strip()
    out = ([f"{BOLD}{WHITE}{ln}{RST}" for ln in wrap(head, width)]
           if head else [])
    if rest:
        out += [f"{SOFT}{ln}{RST}" for ln in wrap(rest, width)]
    return out


_ART_RE = re.compile(r"<<ART:([^>]*)>>\n(.*?)\n<</ART>>", re.S)


def split_art(tail: str):
    """Lift the portrait block out of the text.

    It arrives inside the beat because the text is the one channel that
    survives the queue, the state file and the chat relay. The card is
    where it becomes a picture again.
    """
    m = _ART_RE.search(tail or "")
    if not m:
        return [], "", tail or ""
    art = [ln for ln in m.group(2).split("\n")]
    rest = (tail[:m.start()] + tail[m.end():])
    return art, m.group(1), rest


def _head_block(facts: dict, cols: int, live: dict | None) -> list[str]:
    era = facts.get("era")
    left = f"{ITALIC}{DIM}era {era}{RST}" if era else ""
    lines = [_rule(cols, LABEL, f"era {era}" if era else "")]
    headline = f"{BOLD}{WHITE}Universe born{RST}"
    if era:
        headline += f"{BOLD}{ACCENT}  era {era}{RST}"
    if facts.get("species"):
        headline += f"{BOLD}{SOFT}  ·  {facts['species']} species{RST}"
    lines.append(headline)

    stats = []
    if facts.get("canon"):
        stats.append(f"{GREEN}{facts['canon']} canon{RST}")
    if facts.get("private"):
        stats.append(f"{ACCENT}{facts['private']} private{RST}")
    if live:
        stats.append(f"{SOFT}{live['alive']} alive{RST}")
        stats.append(f"{DIM}tick {live['tick']}{RST}")
    if stats:
        lines.append(f"{DIM}   ·   {RST}".join(stats))
    if facts.get("flavor"):
        lines.append(f"{ITALIC}{SOFT}{facts['flavor']}{RST}")
    lines.append("")
    return lines


def _caption(live: dict | None, note: str = "") -> str:
    if not live:
        return ""
    bits = [f"tick {live['tick']}", f"{live['alive']} alive"]
    total = live.get("lineages_total") or live.get("lineages") or 0
    if total:
        grey = live.get("grey") or 0
        if grey > 0:
            # The dish colours the top-8 and greys the rest. The paint rule
            # is the renderer's business: the reader needs only what the
            # greys MEAN. "Not yet dominant" is the whole message - grey is
            # a rank, never a dead species.
            bits.append(f"{total} lineages · top 8 coloured")
        else:
            bits.append(f"{total} lineages")
    if note:
        bits.append(note)
    return f"{ITALIC}{DIM}  " + "  ·  ".join(bits) + f"{RST}"


def status_panel(stats: dict, dish_rows: int, gutter: int = 0) -> list[str]:
    """The census beside the dish: one row per fact, labels dim, values plain.

    `dish_rows` drives the height so text and picture bottom-align; the
    panel never wraps - every value is composed short enough to fit the
    right column at the widths the card allows.
    """
    rows: list[str] = []
    a = stats.get("ages") or {}
    lineages = stats.get("lineages") or []
    total = stats.get("lineages_total") or len(lineages)

    def _pair(label: str, value: str) -> str:
        return f"{DIM}{label:<11}{RST} {SOFT}{value}{RST}"

    # The panel is printed as the RIGHT column: every row starts with a
    # gutter as wide as the dish will be, so when the dish paints over the
    # left edge nothing collides. Callers may pass gutter=0 to get the
    # bare panel (tests, previews).
    pad = " " * (gutter or 0)

    facts: list[tuple[str, str]] = [
        ("state", f"tick {stats.get('tick', 0)} · {stats.get('population', 0)} alive"
                  f" · peak {stats.get('peak', '?')}"),
    ]
    if stats.get("born") is not None:
        facts.append(("balance", f"{stats['born']} born · {stats['died']} died"))
    if stats.get("avg_energy") is not None:
        facts.append(("energy", f"avg {stats['avg_energy']}"))
    if total:
        top_note = " · top 8 coloured" if (stats.get("grey") or 0) > 0 else ""
        facts.append(("lineages", f"{total} alive{top_note}"))
        for n, c in lineages:
            facts.append(("", f"{c} ×{n}"))
    if a:
        facts.append(("ages", f"{a.get('newborns', 0)} newborn · {a.get('young', 0)} young · "
                              f"{a.get('adults', 0)} adult · {a.get('elders', 0)} elder"))
        verdict = a.get("verdict") or ""
        facts.append(("", f"avg age {a.get('avg_age', 0)} — {verdict}"))
    rows.append("")
    for label, value in facts:
        body = _pair(label, value) if label else f"{'':11} {SOFT}{value}{RST}"
        rows.append(pad + body)
    rows.append("")
    # bottom-align with the dish: pad up to the picture's height
    while len(rows) < dish_rows:
        rows.append("")
    return rows


def _command_table(cols: int) -> list[str]:
    rows = [
        ("/vivarium help", "all commands and shortcuts"),
        ("/vivarium explain", "how text becomes DNA"),
        ("/vivarium status", "census of the dish"),
    ]
    col2 = max(len(a) for a, _ in rows) + 4
    if cols < col2 + 26:
        return [f"  {ACCENT}{a}{RST}" for a, _ in rows]
    return [f"  {ACCENT}{_pad(a, col2)}{RST}{DIM}{b}{RST}" for a, b in rows]


def render(body: str, cols: int, marker: str, live: dict | None = None,
           dish_rows: int = 23, dish: bool = True,
           dish_cols: int = DISH_COLS, era: int | None = None,
           legend: str | None = None) -> dict:
    """Render a beat.

    Returns {text, climb, has_dish, rows}. `climb` is how many rows up
    from the cursor (after the block is printed) the picture's top-left
    sits — computed from the rendered lines, not guessed.
    """
    # A card, not a page: past ~104 columns it stops growing so the
    # measure stays readable on wide kitty windows.
    # Leave the final column empty: a line that fills the last cell makes
    # most terminals wrap, and the card then pushes the prompt down.
    cols = max(40, min(cols - 1, MAX_COLS))
    facts = parse(body, marker)
    is_bang = "Universe born" in facts["head"] or bool(facts.get("era"))
    lines: list[str] = [""]

    if is_bang:
        lines += _head_block(facts, cols, live)
    else:
        # Every beat opens the same way: the wordmark, the hairline, the
        # era on the right. An arrival card is a card too, not a log line.
        head_lines = wrap(facts["head"], cols - 2)
        lines.append(_rule(cols, LABEL, f"era {era}" if era else ""))
        if head_lines:
            lines.append(f"{BOLD}{WHITE}{head_lines[0]}{RST}")
            for extra in head_lines[1:]:
                lines.append(f"{SOFT}{extra}{RST}")
        lines.append("")

    tail_text = facts["tail"]
    if facts.get("art"):
        art_lines, art_eidos = facts["art"], facts.get("art_id", "")
    else:
        art_lines, art_eidos, tail_text = split_art(tail_text)
    two_col = dish and bool(tail_text) and cols >= dish_cols + MIN_GUTTER
    # VIV-80: the blank under the headline STAYS — the user asked for one
    # empty terminal line between the copy and the picture (act 2: after
    # the die-off line, before the dish). It reads as air on a one-column
    # card, but above the dish it is the breathing room that separates
    # words from image.
    spacer_at = len(lines) if two_col else None
    bang_dish_at = None
    if is_bang and dish and spacer_at is None:
        # VIV-80 (the second half of "big bang but no image"): the act-2
        # card carries ALL its copy in the head block, so two_col never
        # fired and the dish had NO reserved rows — the picture could
        # never land. Stack it instead: head block, one empty line (the
        # user's explicit ask), then the dish rows, census table after.
        lines.append("")
        bang_dish_at = len(lines)
        lines += [""] * dish_rows
        spacer_at = bang_dish_at

    if spacer_at is not None and bang_dish_at is not None:
        # Stacked bang dish: the rows are reserved above; the head block
        # already carries the census line, so no second caption and no
        # side column. The paint overlays the reserved rows via climb.
        pass
    elif spacer_at is not None:
        right = cols - dish_cols - 4 - TEXT_INSET
        body_lines: list[str] = []
        if art_lines:
            # The face sits at the top of the column, above the copy, so
            # the first thing read is the creature and the second is
            # where it is. Centered against the dish block: the face
            # hanging at the very top while the dish starts lower reads
            # as a stamp glued to a letter; the middle of the art should
            # meet the middle of the dish.
            art_h = len(art_lines)
            pad = max(0, (dish_rows - art_h) // 2)
            body_lines += [("", True) for _ in range(pad)]
            body_lines += [(ln, True) for ln in art_lines]
            body_lines.append(("", True))
        for i, para in enumerate(p for p in tail_text.split("\n") if p.strip()):
            if i:
                body_lines.append(("", False))
            # Bolding every paragraph turned act 3 into stripes: five
            # bright lines and no hierarchy. The lead is an opening
            # device, so the first two paragraphs get it and the rest
            # read as the argument they are.
            body_lines += [(ln, False)
                           for ln in styled_paragraph(para, right, lead=i < 2)]
        block = max(dish_rows, len(body_lines))
        # centre the copy beside the dish; with the art centered too, the
        # whole column reads as one object between two equal margins.
        top_pad = 1 if dish_rows > len(body_lines) else 0
        pad = "  " + " " * (dish_cols + TEXT_INSET)
        for i in range(block):
            j = i - top_pad
            t, raw = body_lines[j] if 0 <= j < len(body_lines) else ("", False)
            if not t:
                lines.append("")
            elif raw:
                lines.append(pad + t)
            else:
                lines.append(f"{pad}{SOFT}{t}{RST}")
        note = legend or ""
        cap = _caption(live, note)
        if cap:
            lines.append(cap)
    elif tail_text:
        for ln in art_lines:
            lines.append("  " + ln)
        if art_lines:
            lines.append("")
        for ln in wrap(tail_text, cols - 2):
            lines.append(f"  {SOFT}{ln}{RST}")
        # VIV-74: the census (tick / alive / lineages / top coloured) must
        # ride EVERY arrival card, not only the two-column dish layout -
        # on a narrow or non-painting surface the dish drops out and the
        # numbers must not vanish with it.
        if facts.get("art") or art_lines:
            cap = _caption(live, "")
            if cap:
                lines.append(cap)

    lines.append("")
    lines += _command_table(cols)
    lines.append(_rule(cols))
    lines.append(f"{ITALIC}{DIM}  the dish is alive in silence · it speaks only when something is born{RST}")

    climb = 0
    if spacer_at is not None:
        climb = len(lines) - spacer_at
    return {
        "text": "\n".join(lines) + "\n",
        "climb": climb,
        "has_dish": spacer_at is not None,
        "rows": dish_rows if spacer_at is not None else 0,
    }
