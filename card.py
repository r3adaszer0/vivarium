"""The beat, as a card.

The narration used to be a wall of prose with a 339px square dropped into
it: no hierarchy, no margins, and the dish hugging the left edge with the
whole right half of the terminal empty. This module renders the same copy
as a small instrument panel — a header rule, one headline, a stat strip,
the dish on the left with the explanation wrapped into a real measure on
the right, a caption, and a command table.

Everything here is plain ANSI truecolor. Kitty renders it; a terminal
that does not understand SGR still shows readable text, because the
escapes are only ever around the words.

Layout is decided by width:
  * cols >= 96 and a dish present -> two columns (dish left, text right)
  * otherwise                     -> stacked card, no dish
"""
from __future__ import annotations

import re

# ── palette (truecolor, Tokyo Night) ────────────────────────────────────────
FG = "\x1b[38;2;192;202;245m"
WHITE = "\x1b[38;2;236;240;250m"
SOFT = "\x1b[38;2;169;177;214m"
DIM = "\x1b[38;2;110;120;160m"
ACCENT = "\x1b[38;2;125;207;255m"
GREEN = "\x1b[38;2;158;206;106m"
BOLD = "\x1b[1m"
ITALIC = "\x1b[3m"
RST = "\x1b[0m"

_ANSI = re.compile(r"\x1b\[[0-9;]*m")
DISH_COLS = 24          # fallback; the worker passes the real width
MIN_GUTTER = 40
TEXT_INSET = 8          # breathing room between the dish and the copy
MAX_COLS = 104
LABEL = "vivarium"


def plain(s: str) -> str:
    return _ANSI.sub("", s)


def width(s: str) -> int:
    return len(plain(s))


def wrap(text: str, cols: int) -> list[str]:
    """Word wrap that never breaks a word (the old block split 'fingerprint')."""
    out: list[str] = []
    for para in text.split("\n"):
        para = " ".join(para.split())
        if not para:
            out.append("")
            continue
        cur = ""
        for word in para.split(" "):
            cand = f"{cur} {word}".strip()
            if width(cand) <= cols:
                cur = cand
            else:
                if cur:
                    out.append(cur)
                cur = word
        if cur:
            out.append(cur)
    return out


def _rule(cols: int, left: str = "", right: str = "") -> str:
    """A dim hairline with optional labels at the ends."""
    left_s = f" {left} " if left else ""
    right_s = f" {right} " if right else ""
    fill = max(0, cols - width(left_s) - width(right_s))
    line = "─" * fill
    return f"{DIM}{left_s}{line}{right_s}{RST}"


def _pad(s: str, n: int) -> str:
    return s + " " * max(0, n - width(s))


def parse(body: str, marker: str) -> dict:
    """Pull the structured facts out of the copy the acts module produced.

    The copy is generated by us (seeding.onboard_message + acts), so the
    numbers are stable; anything that does not match is simply omitted
    rather than invented.
    """
    head, _, tail = body.partition(marker)
    facts: dict = {"head": head.strip(), "tail": tail.strip()}
    for key, pattern in (
        ("era", r"era (\d+)"),
        ("species", r"Seeded (\d+) species"),
        ("canon", r"(\d+) canon"),
        ("private", r"(\d+) private"),
    ):
        m = re.search(pattern, head, re.IGNORECASE)
        if m:
            facts[key] = int(m.group(1))
    m = re.search(r"(The [^.]*die-off[^.]*\.)", head, re.IGNORECASE)
    if m:
        facts["flavor"] = m.group(1).strip()
    return facts


def _head_block(facts: dict, cols: int, live: dict | None) -> list[str]:
    era = facts.get("era")
    left = f"{ITALIC}{DIM}era {era}{RST}" if era else ""
    lines = [_rule(cols, LABEL, f"era {era}" if era else "")]
    headline = f"{BOLD}{WHITE}Universe born{RST}"
    if era:
        headline += f"{BOLD}{ACCENT}  era {era}{RST}"
    if facts.get("species"):
        headline += f"{BOLD}{SOFT}  ·  {facts['species']} species{RST}"
    lines.append(headline)

    stats = []
    if facts.get("canon"):
        stats.append(f"{GREEN}{facts['canon']} canon{RST}")
    if facts.get("private"):
        stats.append(f"{ACCENT}{facts['private']} private{RST}")
    if live:
        stats.append(f"{SOFT}{live['alive']} alive{RST}")
        stats.append(f"{DIM}tick {live['tick']}{RST}")
    if stats:
        lines.append(f"{DIM}   ·   {RST}".join(stats))
    if facts.get("flavor"):
        lines.append(f"{ITALIC}{SOFT}{facts['flavor']}{RST}")
    lines.append("")
    return lines


def _caption(live: dict | None) -> str:
    if not live:
        return ""
    bits = [f"tick {live['tick']}", f"{live['alive']} alive"]
    if live.get("lineages"):
        bits.append(f"{live['lineages']} lineages")
    return f"{ITALIC}{DIM}  " + "  ·  ".join(bits) + f"{RST}"


def _command_table(cols: int) -> list[str]:
    rows = [
        ("/vivarium help", "all commands and shortcuts"),
        ("/vivarium explain", "how text becomes DNA"),
        ("/vivarium status", "census of the dish"),
    ]
    col2 = max(len(a) for a, _ in rows) + 4
    if cols < col2 + 26:
        return [f"  {ACCENT}{a}{RST}" for a, _ in rows]
    return [f"  {ACCENT}{_pad(a, col2)}{RST}{DIM}{b}{RST}" for a, b in rows]


def render(body: str, cols: int, marker: str, live: dict | None = None,
           dish_rows: int = 23, dish: bool = True,
           dish_cols: int = DISH_COLS) -> dict:
    """Render a beat.

    Returns {text, climb, has_dish, rows}. `climb` is how many rows up
    from the cursor (after the block is printed) the picture's top-left
    sits — computed from the rendered lines, not guessed.
    """
    # A card, not a page: past ~104 columns it stops growing so the
    # measure stays readable on wide kitty windows.
    # Leave the final column empty: a line that fills the last cell makes
    # most terminals wrap, and the card then pushes the prompt down.
    cols = max(40, min(cols - 1, MAX_COLS))
    facts = parse(body, marker)
    is_bang = "Universe born" in facts["head"] or bool(facts.get("era"))
    lines: list[str] = [""]

    if is_bang:
        lines += _head_block(facts, cols, live)
    else:
        # A birth note or any other beat: a rule, the line, the rest dim.
        head_lines = wrap(facts["head"], cols - 2)
        lines.append(_rule(cols, "", ""))
        if head_lines:
            lines.append(f"{BOLD}{WHITE}{head_lines[0]}{RST}")
            for extra in head_lines[1:]:
                lines.append(f"{SOFT}{extra}{RST}")
        lines.append("")

    tail_text = facts["tail"]
    two_col = dish and bool(tail_text) and cols >= dish_cols + MIN_GUTTER
    spacer_at = len(lines) if two_col else None

    if spacer_at is not None:
        right = cols - dish_cols - 4 - TEXT_INSET
        body_lines = wrap(tail_text, right)
        block = max(dish_rows, len(body_lines))
        # centre the text beside the dish instead of leaving it stranded
        # at the top of a 23-row block
        top_pad = 1 if dish_rows > len(body_lines) else 0
        for i in range(block):
            j = i - top_pad
            t = body_lines[j] if 0 <= j < len(body_lines) else ""
            lines.append(f"  {' ' * (dish_cols + TEXT_INSET)}{SOFT}{t}{RST}" if t else "")
        cap = _caption(live)
        if cap:
            lines.append(cap)
    elif tail_text:
        for ln in wrap(tail_text, cols - 2):
            lines.append(f"  {SOFT}{ln}{RST}")

    lines.append("")
    lines += _command_table(cols)
    lines.append(_rule(cols))
    lines.append(f"{ITALIC}{DIM}  the dish is alive in silence · it speaks only when something is born{RST}")

    climb = 0
    if spacer_at is not None:
        climb = len(lines) - spacer_at
    return {
        "text": "\n".join(lines) + "\n",
        "climb": climb,
        "has_dish": spacer_at is not None,
        "rows": dish_rows if spacer_at is not None else 0,
    }
